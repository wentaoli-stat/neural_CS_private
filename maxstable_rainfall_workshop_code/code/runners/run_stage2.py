def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def unknown_context_provenance(reason: str) -> dict[str, Any]:
    return {
        "schema_version": None,
        "status": "unknown_legacy_cache",
        "reason": str(reason),
    }


def decode_context_provenance(saved: Any) -> dict[str, Any]:
    """Read optional cache provenance without breaking pre-metadata caches."""

    if CONTEXT_PROVENANCE_KEY not in saved.files:
        return unknown_context_provenance(
            "cache predates embedded context-generation metadata"
        )
    raw = np.asarray(saved[CONTEXT_PROVENANCE_KEY])
    if raw.shape != ():
        raise ValueError("context provenance must be a scalar JSON string")
    try:
        value = json.loads(str(raw.item()))
    except (TypeError, ValueError, json.JSONDecodeError) as error:
        raise ValueError("context provenance is not valid JSON") from error
    if not isinstance(value, dict):
        raise ValueError("context provenance must decode to an object")
    if (
        value.get("schema_version") is None
        and value.get("status") == "unknown_legacy_cache"
    ):
        return value
    if value.get("schema_version") != CONTEXT_PROVENANCE_SCHEMA_VERSION:
        raise ValueError(
            "unsupported context provenance schema: "
            f"{value.get('schema_version')!r}"
        )
    if value.get("status") != "known":
        raise ValueError("versioned context provenance must have status='known'")
    return value


def validate_reused_context_provenance(
    provenance: dict[str, Any],
    *,
    stage1_checkpoint_sha256: str,
    methods: tuple[str, ...],
    n_train: int,
    n_test: int,
) -> bool:
    """Validate versioned provenance; legacy unknown metadata remains usable."""

    if provenance.get("status") == "unknown_legacy_cache":
        return False
    expected_sha = provenance.get("stage1", {}).get("checkpoint_sha256")
    if expected_sha != str(stage1_checkpoint_sha256):
        raise ValueError(
            "saved contexts were generated by a different Stage-1 checkpoint: "
            f"cache={expected_sha!r}, current={stage1_checkpoint_sha256!r}"
        )
    if provenance.get("method_labels") != list(methods):
        raise ValueError("saved context provenance has incompatible method labels")
    simulation = provenance.get("simulation", {})
    if int(simulation.get("n_train", -1)) != int(n_train) or int(
        simulation.get("n_test", -1)
    ) != int(n_test):
        raise ValueError("saved context provenance has incompatible row counts")
    return True


