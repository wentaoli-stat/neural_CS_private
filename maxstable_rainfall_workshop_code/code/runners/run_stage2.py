    if stage1.get("protocol_version") != SELECTED_PROTOCOL_VERSION:
        raise ValueError("Stage 1 does not match the selected two-arm protocol")
    required = {"linear", "positive_anchor"}
    missing = required.difference(stage1.get("models", {}))
    if missing:
        raise ValueError(f"Stage-1 checkpoint is missing selected arms: {sorted(missing)}")
    methods = tuple(FAIR_METHOD_LABELS[key] for key in ("pilot", "linear", "positive_anchor"))
    stage1_checkpoint_sha256 = file_sha256(args.stage1_checkpoint)
    context_provenance: dict[str, Any]
    context_provenance_validated = False
