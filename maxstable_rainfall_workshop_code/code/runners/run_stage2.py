def pilot_generation_protocol(provenance: dict[str, Any]) -> dict[str, Any]:
    keys = (
        "full_pair_count",
        "pairs_per_group",
        "selected_pair_count",
        "pair_selection_seed",
        "pair_selection",
        "iterations",
        "n_starts",
        "n_refine_starts",
        "start_radius",
        "backtracking_steps",
        "tolerance",
    )
    if provenance.get("status") != "known":
        return {key: "unknown" for key in keys}
    pilot = provenance.get("pilot", {})
    missing = [key for key in keys if key not in pilot]
    if missing:
        raise ValueError(f"context provenance is missing pilot fields: {missing}")
    return {key: pilot[key] for key in keys}


def context_cache_protocol(
    provenance: dict[str, Any], *, reused: bool, validated: bool
) -> dict[str, Any]:
    return {
        "mode": "reused" if reused else "generated",
        "generation_parameters_source": (
            "embedded_cache_metadata"
            if reused and validated
            else ("unknown_legacy_cache" if reused else "current_run")
        ),
        "stage1_checkpoint_match": True if validated else "unknown",
        "provenance": provenance,
    }


def _initialize_simulation_worker(config: Any) -> None:
    global _SIMULATION_CONFIG
    _SIMULATION_CONFIG = config


def _simulate_indexed_dataset(item: tuple[int, np.ndarray, int]):
    index, value, seed_offset = item
    if _SIMULATION_CONFIG is None:
        raise RuntimeError("simulation worker was not initialized")
    return index, simulate_complete_dataset(
        value, _SIMULATION_CONFIG, int(seed_offset) + int(index)
    )


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    if not rows:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def simulate_prior_table(
    rng: np.random.Generator,
    n: int,
    stage1: dict[str, Any],
    seed_offset: int,
    *,
    workers: int = 1,
) -> tuple[np.ndarray, np.ndarray]:
    config = stage1["config"]
    theta = latin_hypercube(
        rng, int(n), config.theta_dim, config.u_min, config.u_max
    )
    if int(workers) <= 1:
        datasets = []
        for index, value in enumerate(theta):
            datasets.append(
                simulate_complete_dataset(value, config, int(seed_offset) + index)
            )
            print(f"Stage-2 complete datasets: {index + 1}/{n}", flush=True)
    else:
        tasks = (
            (index, np.asarray(value, dtype=np.float64), int(seed_offset))
            for index, value in enumerate(theta)
        )
        datasets = [None] * int(n)
        with ProcessPoolExecutor(
            max_workers=int(workers),
            mp_context=mp.get_context("spawn"),
            initializer=_initialize_simulation_worker,
            initargs=(config,),
        ) as executor:
            for completed, (index, dataset) in enumerate(
                executor.map(_simulate_indexed_dataset, tasks, chunksize=1), start=1
            ):
                datasets[index] = dataset
                if completed == 1 or completed % 100 == 0 or completed == int(n):
                    print(
                        f"Stage-2 complete datasets: {completed}/{n} "
                        f"({workers} workers)",
                        flush=True,
                    )
    return theta, np.stack(datasets).astype(np.float32)


def predict_stage1(
    model: torch.nn.Module,
    score: np.ndarray,
    anchor: np.ndarray,
    *,
    device: str,
    batch_size: int,
) -> np.ndarray:
    output: list[np.ndarray] = []
    model.eval()
    with torch.no_grad():
        for start in range(0, len(score), int(batch_size)):
            stop = min(start + int(batch_size), len(score))
            output.append(
                model(
                    torch.as_tensor(
                        score[start:stop], dtype=torch.float32, device=device
                    ),
                    torch.as_tensor(
                        anchor[start:stop], dtype=torch.float32, device=device
                    ),
                )
                .cpu()
                .numpy()
            )
    return np.concatenate(output)


def predict_pair_stage1_streaming_many(
    stage1: dict[str, Any],
    datasets: np.ndarray,
    pilot_w: np.ndarray,
    models: dict[str, torch.nn.Module],
    *,
    device: str,
    feature_chunk_size: int,
    score_batch_size: int,
) -> dict[str, np.ndarray]:
    """Score several pair-local models from one shared feature construction."""

    config = stage1["config"]
    design = stage1["design"]
    _, batch_function = make_annual_pair_feature_function(config, design)
    output: dict[str, list[np.ndarray]] = {key: [] for key in models}
    for start in range(0, len(datasets), int(feature_chunk_size)):
        stop = min(start + int(feature_chunk_size), len(datasets))
        raw = compute_annual_features(
            pilot_w[start:stop],
            datasets[start:stop],
            config,
            design,
            chunk_size=stop - start,
            batch_function=batch_function,
            label="Stage-2 pair-local features at shared pilot",
        )
        score, anchor = transform_pair_inputs(
            raw, pilot_w[start:stop], stage1["stats"], design.group_ids
        )
        for key, model in models.items():
            output[key].append(
                predict_stage1(
                    model,
                    score,
                    anchor,
                    device=device,
                    batch_size=score_batch_size,
                )
            )
    return {key: np.concatenate(value) for key, value in output.items()}


def build_contexts(
    stage1: dict[str, Any],
    datasets: np.ndarray,
    args: argparse.Namespace,
    *,
    device: str,
) -> tuple[np.ndarray, dict[str, np.ndarray], dict[str, np.ndarray]]:
    config = stage1["config"]
    design = stage1["design"]
    pilot_design = stratified_pair_subdesign(
        design,
        int(args.pilot_pairs_per_group),
        int(args.pilot_pair_seed),
    )
    pilot_w, pilot_diagnostics = composite_newton_pilot(
        datasets,
        config,
        pilot_design,
        iterations=int(args.pilot_iterations),
        batch_size=int(args.pilot_batch_size),
        n_starts=int(args.pilot_n_starts),
        n_refine_starts=int(args.pilot_n_refine_starts),
        start_radius=float(args.pilot_start_radius),
        backtracking_steps=int(args.pilot_backtracking_steps),
        convergence_tolerance=float(args.pilot_tolerance),
        return_diagnostics=True,
    )
    if stage1.get("protocol_version") != SELECTED_PROTOCOL_VERSION:
        raise ValueError("Stage 1 does not match the selected two-arm protocol")
    method_keys = ("pilot", "linear", "positive_anchor")
    predictions = predict_pair_stage1_streaming_many(
        stage1,
        datasets,
        pilot_w,
        {key: stage1["models"][key] for key in method_keys if key != "pilot"},
        device=device,
        feature_chunk_size=int(args.feature_chunk_size),
        score_batch_size=int(args.score_batch_size),
    )
    contexts = {
        FAIR_METHOD_LABELS[key]: (
            pilot_w.astype(np.float32)
            if key == "pilot"
            else np.concatenate((pilot_w, predictions[key]), axis=1).astype(np.float32)
        )
        for key in method_keys
    }
    if contexts[PILOT_ONLY_LABEL].shape != (len(datasets), 3):
        raise RuntimeError("bad pilot-only context shape")
    for label in (LINEAR_LABEL, POSITIVE_ANCHOR_LABEL):
        if contexts[label].shape != (len(datasets), 6):
            raise RuntimeError(f"bad score context shape for {label}")
    if not all(np.all(np.isfinite(value)) for value in contexts.values()):
        raise RuntimeError("non-finite shared context")
    return pilot_w, pilot_diagnostics, contexts


def import_sbi():
    try:
        from sbi.inference import NPE
    except ImportError:
        from sbi.inference import SNPE as NPE
    try:
        from sbi.neural_nets import posterior_nn
    except ImportError:
        from sbi.utils.get_nn_models import posterior_nn
    from sbi.utils import BoxUniform

    return NPE, posterior_nn, BoxUniform


def train_npe(
    method: str,
    context: np.ndarray,
    theta: np.ndarray,
    config: Any,
    args: argparse.Namespace,
    *,
    device: str,
) -> dict[str, Any]:
    NPE, posterior_nn, BoxUniform = import_sbi()
    torch.manual_seed(int(args.npe_seed))
    if device.startswith("cuda"):
        torch.cuda.manual_seed_all(int(args.npe_seed))
    theta_unit = torch.as_tensor(
        physical_to_unit(theta, config), dtype=torch.float32
    )
    x = torch.as_tensor(context, dtype=torch.float32)
    density = posterior_nn(
        model=NPE_MODEL,
        z_score_theta="independent",
        z_score_x="independent",
        hidden_features=int(args.npe_hidden),
        num_components=int(args.npe_components),
    )
    prior = BoxUniform(
        low=torch.zeros(config.theta_dim, dtype=torch.float32, device=device),
        high=torch.ones(config.theta_dim, dtype=torch.float32, device=device),
    )
    inference = NPE(
        prior=prior,
        density_estimator=density,
        device=device,
        show_progress_bars=False,
    )
    started = time.time()
    estimator = inference.append_simulations(
        theta_unit, x, data_device="cpu"
    ).train(
        training_batch_size=int(args.npe_batch_size),
        learning_rate=float(args.npe_lr),
        max_num_epochs=int(args.npe_epochs),
        validation_fraction=float(args.validation_fraction),
        stop_after_epochs=int(args.stop_after_epochs),
    )
    posterior = inference.build_posterior(estimator)
    print(f"trained {method} NPE in {time.time() - started:.1f}s", flush=True)
    return {
        "method": method,
        "posterior": posterior,
        "device": device,
        "state_dict": posterior.posterior_estimator.state_dict(),
    }


def posterior_samples(
    fitted: dict[str, Any],
    context: np.ndarray,
    config: Any,
    n: int,
    seed: int,
) -> np.ndarray:
    torch.manual_seed(int(seed))
    if str(fitted["device"]).startswith("cuda"):
        torch.cuda.manual_seed_all(int(seed))
    x = torch.as_tensor(
        context, dtype=torch.float32, device=fitted["device"]
    )
    unit = (
        fitted["posterior"]
        .sample((int(n),), x=x)
        .detach()
        .cpu()
        .numpy()
    )
    return unit_to_physical(unit, config)


def summarize(
    rows: list[dict[str, Any]], methods: tuple[str, ...]
) -> list[dict[str, Any]]:
    output = []
    for method in methods:
        selected = [row for row in rows if row["method"] == method]
        error = np.asarray(
            [row["posterior_mean_error"] for row in selected], dtype=np.float64
        )
        row_summary = {
                "method": method,
                "n_test": len(selected),
                "posterior_mean_rmse_by_coordinate": np.sqrt(
                    np.mean(error**2, axis=0)
                ).tolist(),
                "posterior_mean_l2_rmse_to_generating_parameter": float(
                    np.sqrt(np.mean(np.sum(error**2, axis=1)))
                ),
                "posterior_mean_mae_by_coordinate": np.mean(
                    np.abs(error), axis=0
                ).tolist(),
                "marginal_90_coverage_by_coordinate": np.mean(
                    [row["covers90"] for row in selected], axis=0
                ).tolist(),
                "mean_90_width_by_coordinate": np.mean(
                    [row["width90"] for row in selected], axis=0
                ).tolist(),
                "pilot_converged_count": int(
                    sum(bool(row["pilot_converged"]) for row in selected)
                ),
                "pilot_boundary_count": int(
                    sum(bool(row["pilot_boundary"]) for row in selected)
                ),
            }
        for label, keep in (
            ("pilot_converged", lambda row: bool(row["pilot_converged"])),
            ("pilot_not_converged", lambda row: not bool(row["pilot_converged"])),
            ("pilot_interior", lambda row: not bool(row["pilot_boundary"])),
            ("pilot_boundary", lambda row: bool(row["pilot_boundary"])),
        ):
            subset = [row for row in selected if keep(row)]
            if subset:
                subset_error = np.asarray(
                    [row["posterior_mean_error"] for row in subset], dtype=np.float64
                )
                row_summary[f"{label}_n"] = len(subset)
                row_summary[f"{label}_joint_l2_rmse"] = float(
                    np.sqrt(np.mean(np.sum(subset_error**2, axis=1)))
                )
        output.append(row_summary)
    return output


