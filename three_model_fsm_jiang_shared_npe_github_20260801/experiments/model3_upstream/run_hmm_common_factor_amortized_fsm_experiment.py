    parser.add_argument("--center-p01", type=float, default=0.06)
    parser.add_argument("--center-p11", type=float, default=0.94)
    parser.add_argument("--init-prob", type=float, default=-1.0)
    parser.add_argument("--anchor-p01-min", type=float, default=0.01)
    parser.add_argument("--anchor-p01-max", type=float, default=0.20)
    parser.add_argument("--anchor-p11-min", type=float, default=0.80)
    parser.add_argument("--anchor-p11-max", type=float, default=0.99)
