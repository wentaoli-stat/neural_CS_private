#!/usr/bin/env python3
"""Amortized likelihood-free FSM for the HMM common-factor model.

This script learns a two-dimensional local Fisher-score field

    S(Y, u_anchor),  u_anchor = (logit p01, logit p11),

over a rectangular anchor region.  Each training pair is generated by

    u_anchor ~ stratified anchor design,
    u ~ N(u_anchor, diag(sigma_q**2)),
    Y ~ p(. | u),
    target = (u - u_anchor) / sigma_q**2.

The exact HMM score is evaluation-only.  It is never used by the FSM loss.
"""

